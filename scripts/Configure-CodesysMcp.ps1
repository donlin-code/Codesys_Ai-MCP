#requires -Version 5.1
<#
.SYNOPSIS
Validate an installed official Bridge and print a Codex configuration snippet.
.DESCRIPTION
Default: print only. -SnippetPath creates a new project-local file, never overwrites.
-RegisterCodex adds codesys-sp22 only when that name is absent from the effective Codex configuration.
The script never starts the Bridge or edits/removes existing MCP entries.
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)][string]$Bridge,
    [string]$IdeRoot = 'D:\Program Files\CODESYS 3.5.22.30',
    [string]$SnippetPath,
    [switch]$RegisterCodex,
    [string]$CodexPath
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$serverName = 'codesys-sp22'
$projectRoot = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))

if (-not (Test-Path -LiteralPath $Bridge -PathType Leaf)) {
    throw 'Bridge file does not exist. Copy its actual path from CODESYS Tools > Configure MCP Client after installing the official MCP add-on.'
}
$bridgePath = (Resolve-Path -LiteralPath $Bridge).ProviderPath
if ([IO.Path]::GetFileName($bridgePath) -ine 'CodesysMCPBridge.exe') {
    throw 'Expected the official CodesysMCPBridge.exe, not an IDE executable or an old PLCwright launcher.'
}
$ideDirectory = [IO.Path]::GetFullPath($IdeRoot)
if (-not (Test-Path -LiteralPath (Join-Path $ideDirectory 'Common\CODESYS.exe') -PathType Leaf)) {
    $ideDirectory = Join-Path $ideDirectory 'CODESYS'
}
if (-not (Test-Path -LiteralPath (Join-Path $ideDirectory 'Common\CODESYS.exe') -PathType Leaf)) {
    throw "CODESYS.exe not found under the specified IDE installation: $IdeRoot"
}
$idePrefix = $ideDirectory.TrimEnd('\', '/') + [IO.Path]::DirectorySeparatorChar
if (-not $bridgePath.StartsWith($idePrefix, [StringComparison]::OrdinalIgnoreCase)) {
    throw 'Bridge and IDE must belong to the same installation. Supply the correct -IdeRoot and the path generated by that IDE.'
}
# A TOML basic string needs backslash and quote escaping; never interpolate this into shell code.
$tomlPath = $bridgePath.Replace('\', '\\').Replace('"', '\"')
$snippet = "[mcp_servers.$serverName]`ncommand = `"$tomlPath`"`nargs = []`n"

if ($SnippetPath) {
    $snippetFullPath = if ([IO.Path]::IsPathRooted($SnippetPath)) {
        [IO.Path]::GetFullPath($SnippetPath)
    } else { [IO.Path]::GetFullPath((Join-Path $projectRoot $SnippetPath)) }
    $projectPrefix = $projectRoot.TrimEnd('\', '/') + [IO.Path]::DirectorySeparatorChar
    if (-not $snippetFullPath.StartsWith($projectPrefix, [StringComparison]::OrdinalIgnoreCase)) {
        throw '-SnippetPath must be inside this toolkit project.'
    }
    $parentDirectory = [IO.Path]::GetDirectoryName($snippetFullPath)
    if (-not (Test-Path -LiteralPath $parentDirectory -PathType Container)) {
        throw 'The snippet parent directory must already exist. No existing Codex configuration is overwritten.'
    }
    $stream = [IO.File]::Open($snippetFullPath, [IO.FileMode]::CreateNew, [IO.FileAccess]::Write, [IO.FileShare]::None)
    try {
        $bytes = (New-Object Text.UTF8Encoding($false)).GetBytes($snippet)
        $stream.Write($bytes, 0, $bytes.Length)
    } finally { $stream.Dispose() }
    Write-Host "Created configuration snippet: $snippetFullPath"
} else {
    Write-Output $snippet
}

if ($RegisterCodex) {
    $codexExecutable = if ($CodexPath) {
        if (-not (Test-Path -LiteralPath $CodexPath -PathType Leaf)) { throw '-CodexPath must name an existing executable.' }
        (Resolve-Path -LiteralPath $CodexPath).ProviderPath
    } else { (Get-Command codex -CommandType Application -ErrorAction Stop | Select-Object -First 1).Source }
    # Inspect the effective configuration first; on any discovery/parse failure, fail closed.
    $rawList = & $codexExecutable mcp list --json
    if ($LASTEXITCODE -ne 0) { throw 'Cannot inspect existing Codex MCP configuration; registration was not attempted.' }
    $servers = ConvertFrom-Json -InputObject ($rawList -join "`n")
    $sameName = @($servers | Where-Object { $_.name -eq $serverName })
    if ($sameName.Count -gt 0) {
        throw "An MCP entry named '$serverName' already exists. It was preserved. Inspect it with 'codex mcp get $serverName --json' and update only that entry manually if required."
    }
    $addArguments = @('mcp', 'add', $serverName, '--', $bridgePath)
    & $codexExecutable @addArguments
    if ($LASTEXITCODE -ne 0) { throw 'Codex reported that MCP registration failed.' }
    Write-Host 'Registered codesys-sp22. Registration does not verify licensing, IDE server state, or MCP connectivity.'
    Write-Host 'Enable MCP Server in one SP22 instance, start a new Codex session, and inspect /mcp.'
}
